export type CustomerState = 'SPAWNING' | 'ENTERING' | 'CHOOSING_PRODUCT' | 'MOVING_TO_SHELF' | 'BROWSING' | 'TAKING_PRODUCT' | 'MOVING_TO_CHECKOUT' | 'WAITING_FOR_QUEUE' | 'QUEUEING' | 'WAITING_FOR_CHECKOUT' | 'CHECKOUT' | 'OUT_OF_STOCK' | 'LEAVING' | 'DESPAWNED';

const TRANSITIONS: Record<CustomerState, readonly CustomerState[]> = {
  SPAWNING: ['ENTERING', 'LEAVING'],
  ENTERING: ['CHOOSING_PRODUCT', 'LEAVING'],
  CHOOSING_PRODUCT: ['MOVING_TO_SHELF', 'LEAVING'],
  MOVING_TO_SHELF: ['BROWSING', 'LEAVING'],
  BROWSING: ['TAKING_PRODUCT', 'LEAVING'],
  TAKING_PRODUCT: ['MOVING_TO_CHECKOUT', 'OUT_OF_STOCK', 'LEAVING'],
  MOVING_TO_CHECKOUT: ['QUEUEING', 'WAITING_FOR_QUEUE', 'LEAVING'],
  WAITING_FOR_QUEUE: ['MOVING_TO_CHECKOUT', 'LEAVING'],
  QUEUEING: ['WAITING_FOR_CHECKOUT', 'LEAVING'],
  WAITING_FOR_CHECKOUT: ['CHECKOUT', 'LEAVING'],
  CHECKOUT: ['LEAVING'],
  OUT_OF_STOCK: ['LEAVING'],
  LEAVING: ['DESPAWNED'],
  DESPAWNED: [],
};

export function canTransition(from: CustomerState, to: CustomerState): boolean {
  return TRANSITIONS[from].includes(to);
}
